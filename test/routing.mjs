// Per-role model routing (v0.2.0): merging the plugin's own agents/*.md
// defaults with an optional global file, an optional named profile inside
// it, and an optional docs/foundry.json project override, then generating
// .claude/agents/foundry-<role>.md from the result. foundry_config_show is
// read-only; foundry_agents_sync is the only tool that writes.
//
// Template validation (templates/foundry.config.example.json and
// templates/ccr/*.json) is added alongside the templates themselves, not
// here.

import {
  finish, ok, eq, isError,
  ROOT, mkDir, plannedRepo, withServer,
  readFile, writeFile, hasFile, git, writeGlobalConfig, splitFrontmatter,
} from "./harness.mjs";

const ROLES = ["planner", "implementer", "reviewer", "summarizer"];
const AGENT_FILE = (role) => `.claude/agents/foundry-${role}.md`;

/** The plugin's own default agent file for a role: frontmatter plus body. */
const pluginAgent = (role) => splitFrontmatter(readFile(ROOT, `agents/${role}.md`));

/** A fresh directory to hold a global-config fixture, separate from any project repo. */
const cfgDir = () => mkDir("foundry-cfg-");

// ---------------------------------------------------------------- defaults, no global file

{
  const repo = plannedRepo();
  await withServer(repo, async ({ call }) => {
    const cfg = await call("foundry_config_show");
    eq(cfg.globalConfig, "none", "no global config file is present");
    eq(cfg.profile, null, "no profile is selected");
    eq(cfg.projectOverride, false, "the project's foundry.json carries no roles or permissionMode");
    eq(cfg.permissionMode, "acceptEdits", "the default permission mode is acceptEdits");
    eq(cfg.permissionModeSource, "default", "...with source default");
    eq(cfg.agentsGenerated.join(","), "", "nothing has been generated yet");
    eq(cfg.agentsStale.join(","), "", "nothing to be stale, either");
    for (const role of ROLES) {
      const { frontmatter: fm } = pluginAgent(role);
      eq(cfg.roles[role].model, fm.model, `${role}'s default model matches the plugin agent`);
      eq(cfg.roles[role].effort, fm.effort, `${role}'s default effort matches the plugin agent`);
      eq(cfg.roles[role].source.model, "default", `${role}'s model source is default`);
      eq(cfg.roles[role].source.effort, "default", `${role}'s effort source is default`);
      eq(cfg.roles[role].agent, `foundry-${role}`, `${role}'s reported agent name is foundry-${role}`);
    }
  });
}

// ---------------------------------------------------------------- sync writes four files

{
  const repo = plannedRepo();
  await withServer(repo, async ({ call }) => {
    const r = await call("foundry_agents_sync");
    eq(r.changed.join(","), ROLES.join(","), "sync writes all four roles the first time");
    eq(r.unchanged.join(","), "", "nothing is unchanged yet");
    eq(r.exclude, "added", "the exclude pattern is added");
    eq(r.dir, ".claude/agents", "the reported directory is relative to the project");
    eq(git(repo, ["status", "--porcelain"]), "", "the generated files are excluded, so the tree stays clean");

    const exclude = readFile(repo, ".git/info/exclude");
    ok(exclude.includes(".claude/agents/foundry-*.md"), "the pattern is present in .git/info/exclude");
    eq((exclude.match(/foundry-\*\.md/g) || []).length, 1, "the pattern appears exactly once");

    const comment = "<!-- generated by foundry_agents_sync; edit config, not this file -->\n\n";
    for (const role of ROLES) {
      ok(hasFile(repo, AGENT_FILE(role)), `${AGENT_FILE(role)} exists`);
      const text = readFile(repo, AGENT_FILE(role));
      const { frontmatter: fm, body } = splitFrontmatter(text);
      const plugin = pluginAgent(role);
      eq(fm.name, `foundry-${role}`, `${role}'s generated name`);
      eq(fm.description, plugin.frontmatter.description, `${role}'s description is copied verbatim`);
      eq(fm.model, plugin.frontmatter.model, `${role}'s model matches the plugin default`);
      eq(fm.effort, plugin.frontmatter.effort, `${role}'s effort matches the plugin default`);
      eq(fm.permissionMode, "acceptEdits", `${role}'s permissionMode defaults to acceptEdits`);
      eq((fm.skills || []).join(","), (plugin.frontmatter.skills || []).join(","), `${role}'s skills match the plugin default`);
      eq(fm.color, plugin.frontmatter.color, `${role}'s color matches the plugin default`);
      ok(body.startsWith(comment), `${role}'s body starts with the generated-by comment`);
      const expectedRest = plugin.body.replace(/^\n+/, "").replace(/\s+$/, "") + "\n";
      eq(body.slice(comment.length), expectedRest, `${role}'s body is otherwise the plugin agent's body, trimmed`);
      ok(text.endsWith("\n") && !text.endsWith("\n\n"), `${role}'s generated file ends with exactly one newline`);
    }
  });
}

// ---------------------------------------------------------------- a second sync is a no-op

{
  const repo = plannedRepo();
  await withServer(repo, async ({ call }) => {
    await call("foundry_agents_sync");
    const before = ROLES.map((role) => readFile(repo, AGENT_FILE(role)));

    const r2 = await call("foundry_agents_sync");
    eq(r2.changed.join(","), "", "nothing changes on a second, identical sync");
    eq(r2.unchanged.join(","), ROLES.join(","), "all four roles are reported unchanged");
    eq(r2.exclude, "present", "the exclude pattern is already present");

    const after = ROLES.map((role) => readFile(repo, AGENT_FILE(role)));
    eq(JSON.stringify(after), JSON.stringify(before), "file contents are byte-identical after the second sync");
    const exclude = readFile(repo, ".git/info/exclude");
    eq((exclude.match(/foundry-\*\.md/g) || []).length, 1, "the pattern still appears exactly once");
  });
}

// ---------------------------------------------------------------- foundry_next before/after sync

{
  const repo = plannedRepo();
  await withServer(repo, async ({ call }) => {
    let n = await call("foundry_next");
    eq(n.stage, "implement", "a freshly planned repo has open tasks");
    eq(n.agent, "foundry:implementer", "before sync, the plugin agent name is used");
    const modelBefore = n.model;
    ok(modelBefore, "a resolved model is reported even before sync");

    let s = await call("foundry_status");
    eq(s.agentsGenerated.join(","), "", "nothing generated yet");

    await call("foundry_agents_sync");

    n = await call("foundry_next");
    eq(n.agent, "foundry-implementer", "after sync, the generated agent name is used");
    eq(n.model, modelBefore, "the resolved model is unchanged by sync");

    s = await call("foundry_status");
    eq(s.agentsGenerated.join(","), ROLES.join(","), "status reports all four roles as generated");
  });
}

// ---------------------------------------------------------------- global file overrides

{
  const repo = plannedRepo();
  const globalPath = writeGlobalConfig(cfgDir(), {
    roles: {
      implementer: { model: "claude-sonnet-5" },
      summarizer: { effort: "low" },
    },
    permissionMode: "bypassPermissions",
  });
  await withServer(repo, async ({ call }) => {
    const cfg = await call("foundry_config_show");
    eq(cfg.globalConfig, globalPath, "the global config path is reported");
    eq(cfg.roles.implementer.model, "claude-sonnet-5", "the global file overrides the implementer's model");
    eq(cfg.roles.implementer.source.model, "global", "...with source global");
    eq(cfg.roles.implementer.effort, "medium", "the implementer's effort is untouched (merge is per key)");
    eq(cfg.roles.implementer.source.effort, "default", "...with source default");
    eq(cfg.roles.summarizer.effort, "low", "the global file overrides the summarizer's effort");
    eq(cfg.roles.summarizer.source.effort, "global", "...with source global");
    eq(cfg.roles.planner.source.model, "default", "the planner is untouched");
    eq(cfg.permissionMode, "bypassPermissions", "the global permissionMode wins over the acceptEdits default");
    eq(cfg.permissionModeSource, "global", "...with source global");

    await call("foundry_agents_sync");
    const impl = splitFrontmatter(readFile(repo, AGENT_FILE("implementer"))).frontmatter;
    eq(impl.model, "claude-sonnet-5", "the generated implementer file carries the global model");
    eq(impl.effort, "medium", "...and keeps the default effort");
    eq(impl.permissionMode, "bypassPermissions", "...and carries the global permissionMode");
  }, { env: { FOUNDRY_CONFIG: globalPath } });
}

// ---------------------------------------------------------------- profile selected via env

{
  const repo = plannedRepo();
  const globalPath = writeGlobalConfig(cfgDir(), {
    profiles: {
      local: {
        implementer: { model: "ollama,qwen3.6:35b-a3b" },
        reviewer: { model: "openrouter,deepseek/deepseek-v4-pro" },
      },
    },
  });
  await withServer(repo, async ({ call }) => {
    const cfg = await call("foundry_config_show");
    eq(cfg.profile, "local", "the env-selected profile is reported");
    eq(cfg.profileSource, "env", "...with source env");
    eq(cfg.roles.implementer.model, "ollama,qwen3.6:35b-a3b", "the profile overrides the implementer's model");
    eq(cfg.roles.implementer.effort, undefined, "effort is dropped for a non-Anthropic model");
    eq(cfg.effortDropped.implementer, "medium", "the dropped effort is reported");
    eq(cfg.roles.reviewer.model, "openrouter,deepseek/deepseek-v4-pro", "the profile overrides the reviewer's model");
    eq(cfg.roles.reviewer.effort, undefined, "effort is dropped for the reviewer too");
    eq(cfg.roles.planner.model, "fable", "the planner is untouched by the profile");
    eq(cfg.roles.planner.effort, "high", "...and keeps its effort");

    await call("foundry_agents_sync");
    const impl = splitFrontmatter(readFile(repo, AGENT_FILE("implementer"))).frontmatter;
    eq(impl.model, "ollama,qwen3.6:35b-a3b", "generated implementer file carries the profile's model");
    eq(impl.effort, undefined, "generated implementer file has no effort line");
    const rev = splitFrontmatter(readFile(repo, AGENT_FILE("reviewer"))).frontmatter;
    eq(rev.effort, undefined, "generated reviewer file has no effort line either");
    const pln = splitFrontmatter(readFile(repo, AGENT_FILE("planner"))).frontmatter;
    eq(pln.model, "fable", "generated planner file is untouched");
    eq(pln.effort, "high", "...and keeps its effort");

    const n = await call("foundry_next");
    eq(n.model, "ollama,qwen3.6:35b-a3b", "foundry_next reports the profile's implementer model");
  }, { env: { FOUNDRY_CONFIG: globalPath, FOUNDRY_PROFILE: "local" } });
}

// ---------------------------------------------------------------- profile selected via the file itself

