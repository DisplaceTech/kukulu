// ---------------------------------------------------------------- stale detection

{
  const repo = plannedRepo();
  const dir = cfgDir();

  await withServer(repo, async ({ call }) => {
    await call("foundry_agents_sync");
    const cfg = await call("foundry_config_show");
    eq(cfg.agentsStale.join(","), "", "freshly synced agents are not stale");
  }, { env: { FOUNDRY_CONFIG: writeGlobalConfig(dir, { roles: { implementer: { model: "sonnet" } } }) } });

  // Change the global file without re-syncing.
  const changedPath = writeGlobalConfig(dir, { roles: { implementer: { model: "haiku" } } });
  await withServer(repo, async ({ call }) => {
    let cfg = await call("foundry_config_show");
    eq(cfg.agentsStale.join(","), "implementer", "config_show notices the implementer's generated file is now stale");
    ok(readFile(repo, AGENT_FILE("implementer")).includes("model: sonnet"), "config_show never rewrites the file itself");

    const r = await call("foundry_agents_sync");
    eq(r.changed.join(","), "implementer", "sync catches the stale file up to the new config");

    cfg = await call("foundry_config_show");
    eq(cfg.agentsStale.join(","), "", "nothing is stale after a fresh sync");
  }, { env: { FOUNDRY_CONFIG: changedPath } });
}

// ---------------------------------------------------------------- refusals

{
  const repo = plannedRepo();

  const cases = [
    [{ roles: { tester: { model: "x" } } }, /unknown role 'tester'/, "unknown role name"],
    [{ roles: { planner: { temperature: 1 } } }, /unknown key 'temperature'/, "unknown key in a role"],
    [{ roles: { planner: { effort: "ultra" } } }, /effort/, "bad effort value"],
    [{ permissionMode: "yolo" }, /permissionMode/, "bad permissionMode value"],
    [{ router: "x" }, /unknown key 'router'/, "unknown top-level key"],
  ];
  for (const [obj, re, label] of cases) {
    const globalPath = writeGlobalConfig(cfgDir(), obj);
    await withServer(repo, async ({ call }) => {
      isError(await call("foundry_config_show"), re, `config_show refuses: ${label}`);
      isError(await call("foundry_next"), re, `next refuses with the same kind of error: ${label}`);
      isError(await call("foundry_status"), re, `status refuses with the same kind of error: ${label}`);
      isError(await call("foundry_agents_sync"), re, `agents_sync refuses: ${label}`);
      ok(!hasFile(repo, ".claude/agents"), `.claude/agents is never created on a refused sync (${label})`);
    }, { env: { FOUNDRY_CONFIG: globalPath } });
  }

  {
    const p = writeFile(cfgDir(), "foundry-global.json", "{not json");
    await withServer(repo, async ({ call }) => {
      isError(await call("foundry_config_show"), /not valid JSON/, "invalid JSON in the global config");
    }, { env: { FOUNDRY_CONFIG: p } });
  }

  {
    const globalPath = writeGlobalConfig(cfgDir(), { profiles: { cheap: {} } });
    await withServer(repo, async ({ call }) => {
      isError(await call("foundry_config_show"), /profiles\.nope/, "FOUNDRY_PROFILE names a profile that does not exist");
    }, { env: { FOUNDRY_CONFIG: globalPath, FOUNDRY_PROFILE: "nope" } });
  }

  {
    const globalPath = writeGlobalConfig(cfgDir(), { profile: "nope" });
    await withServer(repo, async ({ call }) => {
      isError(await call("foundry_config_show"), /profiles\.nope/, "the global file's own \"profile\" key names a profile that does not exist");
    }, { env: { FOUNDRY_CONFIG: globalPath } });
  }

  {
    // An unselected profile is still validated, not only the one FOUNDRY_PROFILE picks.
    const globalPath = writeGlobalConfig(cfgDir(), {
      profiles: {
        local: { implementer: { model: "sonnet" } },
        broken: { implementer: { temperature: 1 } },
      },
    });
    await withServer(repo, async ({ call }) => {
      isError(await call("foundry_config_show"), /unknown key 'temperature'/, "an unselected profile is validated too");
    }, { env: { FOUNDRY_CONFIG: globalPath, FOUNDRY_PROFILE: "local" } });
  }
}

// ---------------------------------------------------------------- not a git repository

{
  const dir = mkDir("foundry-plain-routing-");
  await withServer(dir, async ({ call }) => {
    const r = await call("foundry_agents_sync");
    eq(r.changed.join(","), ROLES.join(","), "sync still writes the four files outside a git repository");
    eq(r.exclude, "skipped: not a git repository", "the exclude step is skipped, not an error");
    for (const role of ROLES) ok(hasFile(dir, AGENT_FILE(role)), `${role}'s file is written anyway`);
  });
}

// ---------------------------------------------------------------- description round-trips

{
  const repo = plannedRepo();
  await withServer(repo, async ({ call }) => {
    await call("foundry_agents_sync");
    for (const role of ROLES) {
      const { frontmatter: fm } = splitFrontmatter(readFile(repo, AGENT_FILE(role)));
      eq(fm.description, pluginAgent(role).frontmatter.description, `${role}'s description round-trips through the generated file exactly`);
    }
  });
}

finish();
